export function translateFromDict(dicts, locale, key, vars) {
  const table = dicts[locale] || dicts.es || dicts.en || {};
  let text = table[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), v);
    }
  }
  return text;
}
